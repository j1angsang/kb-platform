def _role_from_position(position: str | None) -> str:
    text = position or ""
    if "管理员" in text:
        return "admin"
    if "领导" in text or "经理" in text or "主管" in text:
        return "leader"
    return "employee"


async def ensure_user(db, username, password, department, position, role=None):
    expected = role or _role_from_position(position)
    result = await db.execute(select(User).where(User.username == username))
    user = result.scalar_one_or_none()
    if user is not None:
        # 已存在也补齐角色，幂等；旧库账号此前全是 employee
        if user.role != expected:
            user.role = expected
            await db.flush()
        return user
    user = User(
        username=username,
        hashed_password=hash_password(password),
        department=department,
        position=position,
        role=expected,
    )
    db.add(user)
    await db.flush()
    await db.refresh(user)
    return user


async def ensure_doc(db, owner, filename, department, content, shared=False):
    data = content.encode("utf-8")
    md5 = hashlib.md5(data).hexdigest()

    result = await db.execute(select(FileInfo).where(FileInfo.md5 == md5))
    file = result.scalars().first()

    if file is None:
        suffix = Path(filename).suffix or ".txt"
        stored_name = uuid.uuid4().hex + suffix
        (STORAGE_DIR / stored_name).write_bytes(data)
        file = FileInfo(
            filename=filename,
            size_bytes=len(data),
            content_type="text/markdown" if suffix == ".md" else "text/plain",
            md5=md5,
            stored_path=stored_name,
            user_id=owner.id,
            department=department,
            is_shared=shared,
        )
        db.add(file)
        await db.flush()
        await db.refresh(file)
    else:
        if shared and not file.is_shared:
            file.is_shared = True
        print(f"  文件已存在: {file.filename} (md5={md5[:8]})")

    result = await db.execute(select(KnowledgeDoc).where(KnowledgeDoc.file_id == file.id))
    doc = result.scalar_one_or_none()
    if doc is None:
        doc = KnowledgeDoc(
            file_id=file.id,
            user_id=owner.id,
            department=department,
            status="approved",
            index_status="indexing",
        )
        db.add(doc)
        await db.flush()
        await db.refresh(doc)
    return doc


async def main():
    async with AsyncSessionLocal() as db:
        users = {}
        for username, password, department, position, role in ACCOUNTS:
            users[username] = await ensure_user(db, username, password, department, position, role)
            print(f"账号: {username}/{password} ({department}, 角色={role})")

        pending = []
        for item in DOCS:
            doc = await ensure_doc(
                db,
                users[item["user"]],
                item["filename"],
                item["department"],
                item["content"],
                shared=item["filename"] in SHARED_FILENAMES,
            )
            pending.append((doc.id, doc.index_status))
            print(f"准备: {item['filename']} -> doc_id={doc.id}, index_status={doc.index_status}")

        await db.commit()

    print("开始向量入库...")
    indexed = 0
    for doc_id, status in pending:
        if status == "ready":
            print(f"  跳过已入库 doc={doc_id}")
            continue
        await index_document(doc_id)
        indexed += 1
    print(f"完成: 新建/重试入库 {indexed} 份文档")


if __name__ == "__main__":
    asyncio.run(main())
